  function applyRules(str, rules) {
    let out = String(str ?? "");
    rules.forEach(([pattern, replacement]) => { out = out.replace(pattern, replacement); });
    return out;
  }

  function text(value) {
    if (!isAz() || value === null || value === undefined) return value;
    const str = String(value);
    if (exactAz[str] !== undefined) return exactAz[str];
    const fieldKey = str.trim().toLowerCase().replace(/[\s-]+/g, "_");
    if (fieldAz[fieldKey]) return fieldAz[fieldKey];
    const fullSentence = applyRules(str, textRules);
    if (fullSentence !== str) return fullSentence;
    return applyRules(str, phraseRules);
  }

  function label(value) {
    if (!isAz() || value === null || value === undefined) return value;
    const str = String(value).trim();
    const key = str.toLowerCase().replace(/[\s-]+/g, "_");
    if (fieldAz[key]) return fieldAz[key];
    if (exactAz[str] !== undefined) return exactAz[str];
    return text(str);
  }

